from string_utility import reverse_word
from string_utility import count_vowels 
from string_utility import is_palindrome

def test_reverse_word_normal():
    assert reverse_word("hello") == "olleh"
    assert reverse_word("world") == "dlrow"
    assert reverse_word("hello world") == "dlrow olleh"

def test_reverse_word_empty():
    assert reverse_word("") == ""

def test_reverse_word_non_string(): 
    assert reverse_word(123) is None

def test_count_vowels_normal():
    assert count_vowels("hello") == 2
    assert count_vowels("world") == 1
    assert count_vowels("aeiou") == 5
    assert count_vowels("bcdfg") == 0
    
def test_count_vowels_empty():
    assert count_vowels("") == 0
    
def test_count_vowels_non_string():
    assert count_vowels(123) is None

def test_is_palindrome_true():
    assert is_palindrome("racecar") is True
    assert is_palindrome("A man a plan a canal Panama") is True
    
def test_is_palindrome_false():
    assert is_palindrome("hello") is False

def test_is_palindrome_non_string():    
    assert is_palindrome(123) is None       














































































































































































































































































































































































































































































































































































































































































































































































































































































































































